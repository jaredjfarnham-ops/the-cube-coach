/* Generate data/2x2-sheets.js — full 2×2 CLL, EG-1 and EG-2 sheets.
   Source: tao-yu/Alg-Trainer js/alg_list.js (saved to _setup/algtrainer-src.js):
     CLL / EG1 / EG2 are { OCLL-shape: [ "alg1/alg2/...", ... per case ] }.
   First alg in each "/"-list is the primary; the rest are alternatives.
   Verified on the headless 3×3 engine treating the 2×2 as its 8 CORNERS:
   set up the case (invertSeq(primary)), apply the candidate, and require all
   corners home under some whole-cube orientation + AUF (edges/centres ignored).
   The case is defined by the alg itself, so EG's swapped bottom layer is handled
   for free. Generated by _setup/gen-2x2-sheets.js — do not hand-edit. */
const fs = require('fs'), vm = require('vm');
const root = 'C:/AI/RubiksCubeCoach/';
const ctx = { console }; vm.createContext(ctx);

const SHAPE = { S:'Sune', AS:'Anti-Sune', PI:'Pi', U:'U', L:'L', T:'T', H:'H' };
const ORDER = ['S','AS','PI','U','L','T','H'];

const out = vm.runInContext(
  'const LESSONS={}; var window={};' +
  ['data/notation.js', 'js/engine.js'].map(f => fs.readFileSync(root + f, 'utf8')).join('\n') +
  '\n' + fs.readFileSync(root + '_setup/algtrainer-src.js', 'utf8') + `
  const clean = s => s.replace(/[()]/g,' ').replace(/2'/g,'2').replace(/\\s+/g,' ').trim();
  const UPS=['','x2','x',"x'","y x'","y' x'"], SP=['','y','y2',"y'"], OR=[];
  UPS.forEach(u=>SP.forEach(s=>OR.push((u+' '+s).trim())));
  const isC = c => Math.abs(c.home.x)+Math.abs(c.home.y)+Math.abs(c.home.z)===3;
  const cornersHome = st => st.cubies().filter(isC).every(c => c.pos.x===c.home.x && c.pos.y===c.home.y && c.pos.z===c.home.z && JSON.stringify(c.ori)===JSON.stringify(I3));
  function solvesCase(primary, cand){
    let pToks, cToks; try{ pToks=invertSeq(primary); cToks=tokenize(cand); cToks.forEach(t=>parse(t)); }catch(e){ return false; }
    for(const hold of OR){ const ht=hold?tokenize(hold):null;
      for(const pre of ['','U','U2',"U'"]){ const st=makeState(); st.reset();
        try{ st.applyTokens(pToks); if(ht)st.applyTokens(ht); if(pre)st.applyTokens(tokenize(pre)); st.applyTokens(cToks); }catch(e){ continue; }
        for(const O of OR){ const ot=O?tokenize(O):null; if(ot)st.applyTokens(ot); const ok=cornersHome(st); if(ot)st.applyTokens(invertSeq(ot)); if(ok) return true; } } }
    return false;
  }
  function simplify(seq){ let toks=tokenize(seq); const base=t=>t.match(/^[A-Za-z]+w?/)[0]; const amt=t=>{let q=/2/.test(t)?2:1; if(/'/.test(t))q=(4-q)%4; return q;};
    for(;;){ const o=[]; let ch=false; for(const t of toks){ if(o.length&&base(o[o.length-1])===base(t)){ const b=base(t),q=(amt(o[o.length-1])+amt(t))%4; o.pop(); ch=true; if(q===1)o.push(b); else if(q===2)o.push(b+'2'); else if(q===3)o.push(b+"'"); } else o.push(t); } toks=o; if(!ch) break; }
    return toks.join(' '); }
  // canonical corner key of a case (for distinctness)
  function caseKey(primary){ let best=null; const inv=invertSeq(primary);
    for(const o of OR) for(const pre of ['','U','U2',"U'"]){ const st=makeState(); st.reset();
      try{ st.applyTokens(inv); if(pre)st.applyTokens(tokenize(pre)); if(o)st.applyTokens(tokenize(o)); }catch(e){ continue; }
      const k=st.cubies().filter(isC).map(c=>[c.home.x,c.home.y,c.home.z,c.pos.x,c.pos.y,c.pos.z,c.ori.flat().join('')].join(',')).sort().join('|');
      if(best===null||k<best) best=k; }
    return best; }

  const SHAPE=${JSON.stringify(SHAPE)}, ORDER=${JSON.stringify(ORDER)};
  function build(SET){
    const cases=[]; let droppedAlts=0;
    for(const g of ORDER){ if(!SET[g]) continue; let n=0;
      SET[g].forEach(caseStr=>{ const algs=caseStr.split('/').map(clean).filter(Boolean); if(!algs.length) return; n++;
        const primary=algs[0]; const seen=new Set([tokenize(primary).join(' ')]); const alts=[];
        algs.slice(1).forEach(a=>{ if(!solvesCase(primary,a)){ droppedAlts++; return; } const s=simplify(a)||a;
          if(!solvesCase(primary,s)){ droppedAlts++; return; } const tk=tokenize(s).join(' '); if(seen.has(tk)) return; seen.add(tk); alts.push(s); });
        const entry={ name:SHAPE[g]+' #'+n, group:SHAPE[g], moves:primary, key:caseKey(primary) };
        if(alts.length) entry.alts=alts.slice(0,5);
        cases.push(entry); });
    }
    // distinctness
    const keys={}; const dups=[];
    cases.forEach(c=>{ if(keys[c.key]) dups.push(c.name+'≡'+keys[c.key]); else keys[c.key]=c.name; delete c.key; });
    return { cases, droppedAlts, dups, distinct:Object.keys(keys).length };
  }
  ({ cll:build(CLL), eg1:build(EG1), eg2:build(EG2) });`,
  ctx, { filename: 'b.js' });

// emit
const META = {
  cll: { set:'cll', path:'2x2/cll/cll-full-sheet', title:'2×2 CLL — Full Sheet',
    intro:'<b>CLL</b> solves the entire 2×2 last layer in one algorithm once a face is built — orienting and permuting the four top corners together. The 40 cases are grouped by their top-orientation shape (Sune, Anti-Sune, Pi, U, L, T, H). Each diagram shows the four corners: top colour = orientation, side tabs = side colours, arrows = the permutation.' },
  eg1: { set:'eg1', path:'2x2/eg/eg1-sheet', title:'2×2 EG-1 — Full Sheet',
    intro:'<b>EG-1</b> solves the last layer in one algorithm when the bottom layer has an <b>adjacent swap</b> (one bar). 40 cases, grouped by top-orientation shape. The diagram shows the top face; you recognise EG-1 by spotting the adjacent swap on the bottom before you start.' },
  eg2: { set:'eg2', path:'2x2/eg/eg2-sheet', title:'2×2 EG-2 — Full Sheet',
    intro:'<b>EG-2</b> solves the last layer in one algorithm when the bottom layer has a <b>diagonal swap</b>. 40 cases, grouped by top-orientation shape. The diagram shows the top face; recognise EG-2 by the diagonal swap on the bottom layer.' },
};
let js = `/* 2×2 CLL / EG-1 / EG-2 — engine-verified (corners) full sheets.
   Algorithms from tao-yu/Alg-Trainer (Justin Taylor CLL, Finn Ickler EG, etc.).
   Generated by _setup/gen-2x2-sheets.js — do not hand-edit. */\n`;
for (const k of ['cll','eg1','eg2']) {
  js += `ALG_SETS['${META[k].set}'] = ${JSON.stringify(out[k].cases)};\n`;
}
js += '\n';
for (const k of ['cll','eg1','eg2']) {
  const m = META[k];
  js += `LESSONS['${m.path}'] = { type:'sheet', kind:'cll', goal:'corners', set:'${m.set}', title:${JSON.stringify(m.title)}, intro:[${JSON.stringify(m.intro)}] };\n`;
}
fs.writeFileSync(root + 'data/2x2-sheets.js', js);

console.log('Wrote data/2x2-sheets.js');
for (const k of ['cll','eg1','eg2']) {
  const r = out[k];
  console.log(`  ${k}: ${r.cases.length} cases (${r.distinct} distinct), ${r.cases.reduce((a,c)=>a+(c.alts?c.alts.length:0),0)} alts, ${r.droppedAlts} alts dropped`);
  if (r.dups.length) console.log('    DUPLICATES:', r.dups);
}
